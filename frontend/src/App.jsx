import React, { useState, useEffect, useRef } from 'react';
import Header from './components/Header';
import MessageInput from './components/MessageInput';
import ProcessVisualizer from './components/ProcessVisualizer';
import HashCard from './components/HashCard';
import RSAKeyCard from './components/RSAKeyCard';
import SignatureCard from './components/SignatureCard';
import VerificationCard from './components/VerificationCard';
import TamperDemoCard from './components/TamperDemoCard';
import EncryptionCard from './components/EncryptionCard';
import ComparisonCard from './components/ComparisonCard';
import ProcessLog from './components/ProcessLog';
import CryptoDetails from './components/CryptoDetails';
import Toast from './components/Toast';

import * as api from './api';

export default function App() {
  const [message, setMessage] = useState('');
  const [activeMessage, setActiveMessage] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [currentStep, setCurrentStep] = useState(0);

  const [hashData, setHashData] = useState(null);
  const [keysData, setKeysData] = useState(null);
  const [signature, setSignature] = useState(null);
  const [verificationResult, setVerificationResult] = useState(null);
  const [ciphertext, setCiphertext] = useState(null);
  const [decryptedMessage, setDecryptedMessage] = useState(null);

  const [logs, setLogs] = useState([]);
  const [toastMessage, setToastMessage] = useState('');
  const initialKeyFetched = useRef(false);

  // Fetch initial session keys on app load (single run)
  useEffect(() => {
    if (initialKeyFetched.current) return;
    initialKeyFetched.current = true;

    async function loadInitialKeys() {
      try {
        const data = await api.generateKeys();
        setKeysData(data);
        addLog('RSA 2048-bit session key pair generated by backend');
      } catch (err) {
        console.warn('Initial backend fetch warning:', err.message);
      }
    }
    loadInitialKeys();
  }, []);

  const addLog = (msg) => {
    const timeStr = new Date().toLocaleTimeString();
    setLogs((prev) => [...prev, { time: timeStr, message: msg }]);
  };

  const triggerToast = (msg) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(''), 3000);
  };

  const handleCopy = (text, label) => {
    if (!text) return;
    navigator.clipboard.writeText(text);
    triggerToast(`${label} copied to clipboard.`);
  };

  const handleLoadDemo = () => {
    const demoText = 'Hello, this is a secure message.';
    setMessage(demoText);
    setError('');
    addLog(`Demo message loaded: "${demoText}"`);
  };

  const handleReset = () => {
    setMessage('');
    setActiveMessage('');
    setError('');
    setCurrentStep(0);
    setHashData(null);
    setSignature(null);
    setVerificationResult(null);
    setCiphertext(null);
    setDecryptedMessage(null);
    setLogs([]);
    addLog('Application state reset successfully');
  };

  const handleRegenerateKeys = async () => {
    setLoading(true);
    try {
      const data = await api.generateKeys();
      setKeysData(data);
      addLog('New RSA 2048-bit key pair generated successfully');
      triggerToast('New RSA 2048-bit key pair generated.');
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleVerifyMessage = async (msgToVerify, sigToVerify) => {
    const data = await api.verifySignature(msgToVerify, sigToVerify, keysData?.publicKey);
    addLog(`Signature verification executed on message "${msgToVerify}": Result ${data.valid ? 'VALID' : 'INVALID'}`);
    return data;
  };

  const handleRunCompleteProcess = async () => {
    if (!message || message.trim() === '') {
      setError('Please enter a message.');
      addLog('Process aborted: Empty message input');
      return;
    }

    setError('');
    setLoading(true);
    setActiveMessage(message);
    addLog(`Initiating complete security process for: "${message}"`);

    try {
      // Step 1: Input Received
      setCurrentStep(1);
      addLog('[Step 1/7] Message received and validated');
      await new Promise((r) => setTimeout(r, 400));

      // Call Backend Complete Process API
      const result = await api.runCompleteProcess(message);

      // Step 2: Hashing
      setCurrentStep(2);
      addLog(`[Step 2/7] SHA-256 hash computed: ${result.hash.substring(0, 16)}...`);
      setHashData({ hash: result.hash, algorithm: 'SHA-256' });
      await new Promise((r) => setTimeout(r, 400));

      // Step 3: Key Check
      setCurrentStep(3);
      addLog('[Step 3/7] RSA 2048-bit Public & Private keys activated');
      if (result.publicKey) {
        setKeysData((prev) => ({ ...prev, publicKey: result.publicKey }));
      }
      await new Promise((r) => setTimeout(r, 400));

      // Step 4: Digital Signature
      setCurrentStep(4);
      setSignature(result.signature);
      addLog('[Step 4/7] RSA-PSS digital signature generated');
      await new Promise((r) => setTimeout(r, 400));

      // Step 5: Signature Verification
      setCurrentStep(5);
      setVerificationResult(result.signatureValid);
      addLog(`[Step 5/7] Signature cryptographically verified: ${result.signatureValid ? 'VALID' : 'INVALID'}`);
      await new Promise((r) => setTimeout(r, 400));

      // Step 6: Encryption
      setCurrentStep(6);
      setCiphertext(result.ciphertext);
      addLog('[Step 6/7] Plaintext encrypted using RSA-OAEP + SHA-256');
      await new Promise((r) => setTimeout(r, 400));

      // Step 7: Decryption
      setCurrentStep(7);
      setDecryptedMessage(result.decryptedMessage);
      addLog('[Step 7/7] Ciphertext decrypted using RSA Private Key successfully');

      triggerToast('Complete security workflow executed successfully!');
    } catch (err) {
      setError(err.message);
      addLog(`Error executing security process: ${err.message}`);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="app-container">
      <Header />

      <main>
        {/* Section 1: Message Input */}
        <MessageInput
          message={message}
          setMessage={setMessage}
          onRunProcess={handleRunCompleteProcess}
          onLoadDemo={handleLoadDemo}
          onReset={handleReset}
          loading={loading}
          error={error}
        />

        {/* Section 2: Visual Flowchart */}
        <ProcessVisualizer
          currentStep={currentStep}
          activeMessage={activeMessage}
        />

        {/* Section 3: SHA-256 Hashing Card */}
        <HashCard
          message={activeMessage || message}
          hashData={hashData}
          onCopy={handleCopy}
        />

        {/* Section 4: RSA Key Pair Card */}
        <RSAKeyCard
          keysData={keysData}
          onRegenerateKeys={handleRegenerateKeys}
          onCopy={handleCopy}
          loading={loading}
        />

        {/* Section 5: Digital Signature Card */}
        <SignatureCard
          signature={signature}
          onCopy={handleCopy}
        />

        {/* Section 6: Signature Verification Card */}
        <VerificationCard
          verificationResult={verificationResult}
          message={activeMessage}
          signature={signature}
        />

        {/* Section 7: Interactive Tamper Detection Demo */}
        <TamperDemoCard
          signature={signature}
          initialMessage={activeMessage || 'Hello World'}
          onVerify={handleVerifyMessage}
        />

        {/* Section 8: RSA Encryption & Decryption Card */}
        <EncryptionCard
          message={activeMessage}
          ciphertext={ciphertext}
          decryptedMessage={decryptedMessage}
          onCopy={handleCopy}
        />

        {/* Section 9: Encryption vs Digital Signature Comparison Matrix */}
        <ComparisonCard />

        {/* Section 10: Security Process Audit Log */}
        <ProcessLog logs={logs} />

        {/* Section 11: Technical Parameter Specifications Drawer */}
        <CryptoDetails />
      </main>

      {/* Floating Copy Feedback Toast */}
      <Toast message={toastMessage} />
    </div>
  );
}
